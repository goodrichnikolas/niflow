def cleanup_sandboxes(client: Any, prefix: str = SANDBOX_PREFIX) -> int:
    """Delete every leftover fuzz sandbox on the target; returns how many went.

    A long live sweep must not litter someone's canvas: NiFi keeps the
    half-created group behind when a push fails mid-import, and a delete can
    409 while the server is still settling — so this runs a few passes and
    never raises.
    """
    removed = 0
    for _ in range(3):
        try:
            stale = [component["id"] for _, component in client.walk_groups()
                     if str(component.get("name") or "").startswith(prefix)]
        except Exception:  # pragma: no cover - inventory is a cheap GET
            return removed
        if not stale:
            break
        progressed = False
        for pg_id in stale:
            try:
                client.delete_group(pg_id)
            except Exception:
                continue
            removed += 1
            progressed = True
        if not progressed:
            break
    return removed


@dataclass
class SweepConfig:
    tier: int = 1
    count: int = 0
    seed: int = 0
    kinds: Tuple[str, ...] = KINDS
    type_pattern: Optional[str] = None
    out_dir: Path = DEFAULT_OUT_DIR
    resume: bool = False
    target_majors: Tuple[int, ...] = (1,)
    max_repros_per_signature: int = 3
    max_failures: int = 0
    keep_sandboxes: bool = False
    quiet: bool = False

    def to_dict(self) -> Dict[str, Any]:
        data = dict(self.__dict__)
        data["out_dir"] = str(self.out_dir)
        data["kinds"] = list(self.kinds)
        data["target_majors"] = list(self.target_majors)
        return data


@dataclass
class Report:
    config: SweepConfig
    results: List[CaseResult] = field(default_factory=list)
    skipped: int = 0
    elapsed: float = 0.0
    stopped_early: bool = False
    sandboxes_removed: int = 0

    @property
    def counts(self) -> Dict[str, int]:
        counts = {PASSED: 0, NIFLOW_BUG: 0, NIFI_REJECTED: 0}
        for result in self.results:
            counts[result.status] = counts.get(result.status, 0) + 1
        return counts

    def by_signature(self, classification: str = NIFLOW_BUG) -> Dict[str, List[CaseResult]]:
        grouped: Dict[str, List[CaseResult]] = {}
        for result in self.results:
            for finding in result.findings:
                if finding.classification != classification:
                    continue
                grouped.setdefault(finding.signature, []).append(result)
        return dict(sorted(grouped.items(), key=lambda kv: -len(kv[1])))


def run_case(case: Case, config: SweepConfig, client: Any = None) -> CaseResult:
    """Run one case at the configured tier."""
    if config.tier >= 3 and client is not None:
        return check_live_roundtrip(case, client)
    if config.tier >= 2 and client is not None:
        return check_live_validate(case, client)
    return check_offline(case, target_majors=config.target_majors)


def _load_previous(path: Path) -> Dict[str, Dict[str, Any]]:
    previous: Dict[str, Dict[str, Any]] = {}
    if not path.exists():
        return previous
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            record = json.loads(line)
        except json.JSONDecodeError:  # truncated final line from a hard kill
            continue
        previous[record["case_id"]] = record
    return previous


def _result_from_record(record: Dict[str, Any]) -> CaseResult:
    case = Case(record["kind"], record["spec"])
    result = CaseResult(case, status=record.get("status", PASSED),
                        elapsed=record.get("elapsed", 0.0),
                        observations=record.get("observations", []))
    result.findings = [Finding(**f) for f in record.get("findings", [])]
    return result


def sweep(config: SweepConfig, client: Any = None,
          progress: Optional[Callable[[int, int, CaseResult], None]] = None) -> Report:
    """Run a whole sweep, streaming results to disk so it survives a restart."""
    out_dir = Path(config.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    results_path = out_dir / "results.jsonl"

    previous = _load_previous(results_path) if config.resume else {}
    if not config.resume and results_path.exists():
        results_path.unlink()
    (out_dir / "run.json").write_text(json.dumps({
        "config": config.to_dict(),
        "catalog": getattr(_catalog(), "CATALOG_META", {}),
        "started": time.strftime("%Y-%m-%d %H:%M:%S"),
    }, indent=2), encoding="utf-8")

    cases = generate_cases(seed=config.seed, kinds=config.kinds,
                           type_pattern=config.type_pattern, count=config.count)
    report = Report(config=config)
    repro_counts: Dict[str, int] = {}
    started = time.perf_counter()

    # The emitters log a warning per cross-version property drop; at this
    # volume that is pure noise (the drops are recorded as observations).
    logger = logging.getLogger("niflow")
    previous_level = logger.level
    logger.setLevel(logging.ERROR)
    try:
        with results_path.open("a", encoding="utf-8") as handle:
            for index, case in enumerate(cases, 1):
                record = previous.get(case.case_id)
                if record is not None:
                    result = _result_from_record(record)
                    report.results.append(result)
                    report.skipped += 1
                    continue
                try:
                    result = run_case(case, config, client)
                except Exception as exc:  # harness bug — record, never abort
                    result = CaseResult(case)
                    result.add(_exception_finding("harness", exc))
                report.results.append(result)
                handle.write(json.dumps(result.to_dict(), ensure_ascii=False) + "\n")
                handle.flush()

                for finding in result.findings:
                    if finding.classification != NIFLOW_BUG:
                        continue
                    seen = repro_counts.get(finding.signature, 0)
                    if seen < config.max_repros_per_signature:
                        repro_counts[finding.signature] = seen + 1
                        write_repro(result, out_dir)
                    break
                if progress is not None:
                    progress(index, len(cases), result)
                if config.max_failures and report.counts[NIFLOW_BUG] >= config.max_failures:
                    report.stopped_early = True
                    break
    finally:
        logger.setLevel(previous_level)

    report.elapsed = time.perf_counter() - started
    if client is not None and not config.keep_sandboxes:
        report.sandboxes_removed = cleanup_sandboxes(client)
    (out_dir / "summary.txt").write_text(format_report(report), encoding="utf-8")
    return report


def replay(case_id: str, config: SweepConfig, client: Any = None) -> CaseResult:
    """Re-run exactly one case, by id — the narrowing loop after a big sweep."""
    case = find_case(case_id, config)
    if case is None:
        raise LookupError(
            f"case {case_id!r} not found — it is not in {config.out_dir}/results.jsonl "
            f"and the current --seed/--kinds/--types do not generate it")
    return run_case(case, config, client)


def find_case(case_id: str, config: SweepConfig) -> Optional[Case]:
    """Locate a case by id: saved repro first, then the run log, then regenerate."""
    repro = Path(config.out_dir) / "repro" / case_id / "case.json"
    if repro.exists():
        record = json.loads(repro.read_text(encoding="utf-8"))
        return Case(record["kind"], record["spec"])
    for record in _load_previous(Path(config.out_dir) / "results.jsonl").values():
        if record["case_id"] == case_id:
            return Case(record["kind"], record["spec"])
    for case in generate_cases(seed=config.seed, kinds=config.kinds,
                               type_pattern=config.type_pattern):
        if case.case_id == case_id:
            return case
    return None


