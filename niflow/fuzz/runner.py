"""Running a sweep: repro files, resumable results, replay, and the report.

A sweep streams one JSON record per case to ``<out>/results.jsonl`` and flushes
after each one, so a multi-hour run survives a kill and ``--resume`` picks it
up. Each distinct root-cause signature writes up to
``max_repros_per_signature`` standalone repro directories — a runnable flow
module, the case spec, and the findings — so a bug can be handed to `niflow
validate` / `push` directly, or replayed with ``niflow fuzz --replay <id>``.
"""
from __future__ import annotations

import json
import logging
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Callable, Dict, List, Optional, Tuple

from niflow.fuzz.cases import (
    DEFAULT_OUT_DIR,
    KINDS,
    SANDBOX_PREFIX,
    NIFI_REJECTED,
    NIFLOW_BUG,
    PASSED,
    Case,
    _catalog,
    generate_cases,
)
from niflow.fuzz.checks import (
    CaseResult,
    Finding,
    _exception_finding,
    check_live_roundtrip,
    check_live_validate,
    check_offline,
)
