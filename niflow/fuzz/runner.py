def format_report(report: Report) -> str:
    """The end-of-sweep summary: counts, then findings grouped by root cause."""
    counts = report.counts
    total = len(report.results)
    lines = [
        f"niflow fuzz — tier {report.config.tier}, seed {report.config.seed}, "
        f"{total} case(s) in {report.elapsed:.1f}s"
        + (f" ({report.skipped} resumed)" if report.skipped else ""),
        "",
        f"  passed         {counts[PASSED]:>6}",
        f"  niflow bug     {counts[NIFLOW_BUG]:>6}",
        f"  NiFi rejected  {counts[NIFI_REJECTED]:>6}",
    ]
    if report.stopped_early:
        lines.append("  (stopped early: --max-failures reached)")
    if report.sandboxes_removed:
        lines.append(f"  ({report.sandboxes_removed} leftover sandbox group(s) "
                     "cleaned up)")

    for classification, title in ((NIFLOW_BUG, "niflow bugs"),
                                  (NIFI_REJECTED, "NiFi rejections")):
        grouped = report.by_signature(classification)
        if not grouped:
            continue
        lines += ["", f"{title} — {len(grouped)} distinct signature(s):"]
        for signature, results in grouped.items():
            first = results[0]
            finding = next(f for f in first.findings if f.signature == signature)
            lines += [
                "",
                f"  [{signature}]  ×{len(results)}",
                f"    {finding.message}",
                f"    first case: {first.case.case_id}  ({_spec_summary(first.case)})",
                f"    replay:     niflow fuzz --replay {first.case.case_id}",
                f"    repro:      {Path(report.config.out_dir) / 'repro' / first.case.case_id / 'flow.py'}",
            ]

    disagreements = [o for result in report.results for o in result.observations
                     if o.get("kind") == "validate_disagreement"]
    if disagreements:
        static_only = sum(1 for o in disagreements if o["direction"] == "static_only")
        lines += [
            "",
            f"validate disagreements not blamed on niflow ({len(disagreements)}):",
            f"  {len(disagreements) - static_only} the server flags and niflow does "
            "not (required/allowable rules differ per NiFi line, or the check is "
            "outside what validate claims)",
        ]
        if static_only:
            lines.append(
                f"  {static_only} niflow flags and the server does not — the catalog "
                "is from the other NiFi line; re-run with a matching catalog "
                "(`make catalog` / `make catalog-v1`) to judge these")

    untranslatable = sorted({
        observation["type"]
        for result in report.results for observation in result.observations
        if observation.get("kind") == "no_cross_version_data"
    })
    if untranslatable:
        # "No 1.x data" has two very different causes and the sweep used to
        # report them as one number. A type that does not EXIST on 1.x has
        # nothing to translate and is not a gap — niflow already refuses it with
        # a "type does not exist on NiFi 1.x" warning. A type that exists there
        # and still has no data is the real hole.
        from niflow.compat import type_missing_on

        absent = [t for t in untranslatable if type_missing_on(t, 1)]
        holes = [t for t in untranslatable if t not in set(absent)]
        if holes:
            lines += [
                "",
                f"types with NO 1.x compatibility data ({len(holes)}) — a "
                "renamed property on these is emitted under its 2.x key and lands on a "
                "1.x server as an inert dynamic property:",
                "  " + ", ".join(t.rsplit(".", 1)[-1] for t in holes[:20])
                + (" …" if len(holes) > 20 else ""),
            ]
        if absent:
            lines += [
                "",
                f"types that do not exist on 1.x ({len(absent)}) — nothing to "
                "translate; a flow using these cannot be pushed to a 1.x server "
                "at all (`niflow validate --target-version 1.x` says so):",
                "  " + ", ".join(t.rsplit(".", 1)[-1] for t in absent[:20])
                + (" …" if len(absent) > 20 else ""),
            ]

    drops = _drop_summary(report)
    if drops:
        lines += ["", f"cross-version property drops (informational, {len(drops)} type(s)):"]
        for type_str, keys in list(drops.items())[:15]:
            lines.append(f"  {type_str}: {', '.join(sorted(keys)[:6])}"
                         + (" …" if len(keys) > 6 else ""))
        if len(drops) > 15:
            lines.append(f"  … and {len(drops) - 15} more type(s)")
    return "\n".join(lines)


def _spec_summary(case: Case) -> str:
    spec = case.spec
    parts = [f"{key}={_short(value)}" for key, value in sorted(spec.items())
             if key != "properties"]
    if "properties" in spec:
        parts.append(f"props={len(spec['properties'])}")
    return " ".join(parts)


def _short(value: Any) -> str:
    text = str(value)
    return text.rsplit(".", 1)[-1] if "." in text and " " not in text else text


def _drop_summary(report: Report) -> Dict[str, set]:
    drops: Dict[str, set] = {}
    for result in report.results:
        for observation in result.observations:
            if observation.get("kind") != "cross_version_drop":
                continue
            drops.setdefault(observation["type"], set()).update(observation["properties"])
    return dict(sorted(drops.items()))
