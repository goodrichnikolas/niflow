_REPRO_TEMPLATE = '''"""niflow fuzz repro — case {case_id} ({kind}).

Generated by `niflow fuzz`. This module is a normal niflow flow file: it
exposes a top-level `flow`, so every niflow command works on it.

    niflow validate {path}
    niflow plan {path}
    niflow push {path}
    niflow fuzz --replay {case_id}

What failed:
{failures}
"""
from niflow.fuzz import build_case_flow

KIND = {kind!r}
SPEC = {spec}

flow = build_case_flow(KIND, SPEC)
'''


def write_repro(result: CaseResult, out_dir: Path) -> Path:
    """Write a minimal, standalone, runnable reproduction of a failing case."""
    directory = Path(out_dir) / "repro" / result.case.case_id
    directory.mkdir(parents=True, exist_ok=True)
    flow_path = directory / "flow.py"
    failures = "\n".join(
        f"  * [{f.check}] {f.message}" for f in result.findings) or "  (none)"
    flow_path.write_text(_REPRO_TEMPLATE.format(
        case_id=result.case.case_id,
        kind=result.case.kind,
        spec=_pretty_spec(result.case.spec),
        path=flow_path,
        failures=failures,
    ), encoding="utf-8")
    (directory / "case.json").write_text(
        json.dumps(result.to_dict(), indent=2, ensure_ascii=False), encoding="utf-8")

    details = "\n\n".join(
        f"### {f.check} [{f.classification}] {f.signature}\n{f.message}\n\n{f.detail}"
        for f in result.findings)
    (directory / "findings.txt").write_text(details, encoding="utf-8")

    # A best-effort expanded form: the same flow written out as plain niflow
    # code, for hand-editing. Skipped when the emitter itself is the casualty.
    try:
        from niflow.formats import to_python

        (directory / "flow_expanded.py").write_text(
            to_python(result.case.build(),
                      module_docstring=f"Expanded repro for fuzz case {result.case.case_id}."),
            encoding="utf-8")
    except Exception:
        pass
    return flow_path


def _pretty_spec(spec: Dict[str, Any]) -> str:
    return json.dumps(spec, indent=4, ensure_ascii=False).replace(": true", ": True") \
        .replace(": false", ": False").replace(": null", ": None")


